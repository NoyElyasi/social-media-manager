/**
 * סורקת את הטקסט אחרי מילות המפתח של כל נושא זמין (מתוך availableThemes —
 * הרשימה שהמשתמשת קבעה בהגדרות, לא בהכרח כל הנושאים ב-THEME_KEYWORDS),
 * ומחזירה את הנושא עם הכי הרבה התאמות. שוויון/אין התאמה בכלל = null (לא
 * מנחשת סתם — עדיפה "אחר" נכון על ניחוש שגוי).
 */
export function detectThemeFromText(text: string, availableThemes: string[]): string | null {
  let bestTheme: string | null = null;
  let bestCount = 0;

  for (const theme of availableThemes) {
    const keywords = THEME_KEYWORDS[theme];
    if (!keywords) continue;
    const count = keywords.filter((kw) => text.includes(kw)).length;
    if (count > bestCount) {
      bestCount = count;
      bestTheme = theme;
    }
  }

  return bestTheme;
}
